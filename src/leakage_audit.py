"""Write reports/leakage.md: evidence behind src/feature_policy.py and the cohort/split rules.

1. Univariate AUC of every column against label_broad on the train split
   (out-of-fold target encoding for categoricals, so high-cardinality columns
   are not flattered), next to its policy tier.
2. Trials registered after they ended (excluded by src/label.py).
3. Text: how often descriptions report the trial's course, before and after
   scrub_text, and what a bag-of-words model learns from raw vs scrubbed text.
4. Trials still running per start year (reports/censoring_by_year.csv).
5. Split sizes and label rates.

Usage:
    python src/leakage_audit.py
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import roc_auc_score
from sklearn.model_selection import KFold

from feature_policy import BLOCKED, CAUTION, POST_HOC_TEXT, TIERS, scrub_text
from label_report import md
from split import SPLITS, outcome_known_by

TARGET = "label_broad"


def auc(y: np.ndarray, x: pd.Series) -> float:
    """Direction-free AUC (max(AUC, 1-AUC)) on rows where x is known."""
    x = pd.to_numeric(x, errors="coerce").astype(float)
    m = x.notna().to_numpy()
    if m.sum() < 50 or x[m].nunique() < 2 or len(np.unique(y[m])) < 2:
        return np.nan
    a = roc_auc_score(y[m], x[m])
    return max(a, 1 - a)


def oof_target_encode(s: pd.Series, y: np.ndarray, folds: int = 5, smoothing: float = 20.0) -> pd.Series:
    """Out-of-fold mean-target encoding, smoothed toward the prior."""
    s = s.astype(str).reset_index(drop=True)
    out = np.empty(len(s))
    prior = y.mean()
    for tr, te in KFold(folds, shuffle=True, random_state=0).split(s):
        st = pd.DataFrame({"k": s.iloc[tr].to_numpy(), "y": y[tr]}).groupby("k").y.agg(["sum", "count"])
        enc = (st["sum"] + smoothing * prior) / (st["count"] + smoothing)
        out[te] = s.iloc[te].map(enc).fillna(prior).to_numpy()
    return pd.Series(out)


def column_signal(df: pd.DataFrame, y: np.ndarray) -> pd.DataFrame:
    rows = []
    for col in df.columns:
        if col == "nct_id":
            continue
        s = df[col].reset_index(drop=True)
        first = s.dropna().iloc[0] if s.notna().any() else None
        if isinstance(first, (list, np.ndarray)):
            kind, x = "list (length)", s.map(lambda v: len(v) if v is not None else np.nan)
        elif pd.api.types.is_datetime64_any_dtype(s):
            kind, x = "date (year)", s.dt.year
        elif pd.api.types.is_bool_dtype(s) or pd.api.types.is_numeric_dtype(s):
            kind, x = "numeric", s.astype(float)
        elif s.nunique() > 200:
            kind, x = "text (length)", s.fillna("").str.len()
        else:
            kind, x = "categorical (OOF target enc.)", oof_target_encode(s.fillna("NA"), y)
        rows.append({
            "column": col, "tier": TIERS.get(col, "unknown"), "kind": kind,
            "AUC": auc(y, x), "AUC of missingness": auc(y, s.isna().astype(float)),
            "missing": s.isna().mean(),
            "reason": BLOCKED.get(col) or CAUTION.get(col) or "",
        })
    return pd.DataFrame(rows).set_index("column")


def text_model_auc(train_text: pd.Series, y_tr: np.ndarray, val_text: pd.Series, y_va: np.ndarray, top: int = 15):
    vec = TfidfVectorizer(min_df=5, max_features=50000, sublinear_tf=True, stop_words="english")
    Xtr, Xva = vec.fit_transform(train_text), vec.transform(val_text)
    clf = LogisticRegression(C=1.0, max_iter=2000, class_weight="balanced").fit(Xtr, y_tr)
    a = roc_auc_score(y_va, clf.predict_proba(Xva)[:, 1])
    vocab = np.array(vec.get_feature_names_out())
    order = np.argsort(clf.coef_[0])
    return a, list(vocab[order[:top]]), list(vocab[order[-top:][::-1]])


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--trials", default="data/processed/trials.parquet", type=Path)
    ap.add_argument("--labels", default="data/processed/labels.parquet", type=Path)
    ap.add_argument("--censoring", default="reports/censoring_by_year.csv", type=Path)
    ap.add_argument("--out", default="reports/leakage.md", type=Path)
    args = ap.parse_args()

    trials = pd.read_parquet(args.trials)
    lab = pd.read_parquet(args.labels)
    d = trials.merge(lab[["nct_id", "in_cohort", "split", "exclusion_reason", TARGET]], on="nct_id")
    cohort = d[d.in_cohort].reset_index(drop=True)
    train = cohort[cohort.split.eq("train")].reset_index(drop=True)
    val = cohort[cohort.split.eq("val")].reset_index(drop=True)
    y_tr, y_va = train[TARGET].to_numpy(), val[TARGET].to_numpy()

    out = ["# Leakage audit", "", "_Generated by `src/leakage_audit.py`. Do not edit by hand._", "",
           f"Target: `{TARGET}` (1 = completed). All numbers on the train split ({len(train):,} trials) unless noted. "
           "AUC is direction-free (max(AUC, 1 - AUC)): 0.5 = no signal.", ""]

    # 1. per-column signal
    sig = column_signal(train.drop(columns=["in_cohort", "split", "exclusion_reason", TARGET]), y_tr)
    derived = pd.DataFrame([
        {"column": "duration (completion - start)", "tier": "blocked", "kind": "derived",
         "AUC": auc(y_tr, (train.completion_date - train.start_date).dt.days), "reason": "uses the end date"},
        {"column": "registration lag (first post - start)", "tier": "blocked", "kind": "derived",
         "AUC": auc(y_tr, (train.first_post_date - train.start_date).dt.days), "reason": "survival to registration"},
    ]).set_index("column")
    sig = pd.concat([sig, derived]).sort_values("AUC", ascending=False)
    out += ["## 1. Signal in each column", "",
            "A blocked column with a high AUC is leakage we avoided. A caution column with a high AUC deserves an "
            "ablation in Phase 4.", "", md(sig.fillna("")), ""]

    # 2. registered after the end
    window = d[d.start_date.dt.year.between(min(lo for lo, _ in SPLITS.values()), max(hi for _, hi in SPLITS.values()))
               & d.overall_status.isin(["COMPLETED", "TERMINATED"])]
    end = window.primary_completion_date.fillna(window.completion_date)
    late = window.first_post_date > end
    reg = pd.DataFrame({
        "trials": [late.sum(), (~late).sum()],
        "share": [late.mean(), (~late).mean()],
        "completed rate": [window.loc[late, "overall_status"].eq("COMPLETED").mean(),
                           window.loc[~late, "overall_status"].eq("COMPLETED").mean()],
    }, index=pd.Index(["registered after the end (excluded)", "registered before the end"], name=""))
    out += ["## 2. Trials registered after they ended", "",
            "Completed/terminated trials starting in the cohort years. A trial registered after its end could not have "
            "been predicted at start, and nearly all of them are completed, so they are excluded from the cohort.", "",
            md(reg), ""]

    # 3. text
    rows = {}
    for col in ["brief_title", "official_title", "brief_summary", "detailed_description", "eligibility_criteria"]:
        raw = train[col].fillna("")
        scrubbed = raw.map(scrub_text)
        has_post_hoc = lambda s: bool(POST_HOC_TEXT.search(s))
        hit_raw, hit_scr = raw.map(has_post_hoc), scrubbed.map(has_post_hoc)
        removed = 1 - scrubbed.str.len() / raw.str.len().replace(0, np.nan)
        rows[col] = {
            "post-hoc sentence, terminated": hit_raw[y_tr == 0].mean(),
            "post-hoc sentence, completed": hit_raw[y_tr == 1].mean(),
            "after scrub, terminated": hit_scr[y_tr == 0].mean(),
            "after scrub, completed": hit_scr[y_tr == 1].mean(),
            "text removed, terminated": removed[y_tr == 0].mean(),
            "text removed, completed": removed[y_tr == 1].mean(),
        }
    out += ["## 3. Text written after the trial", "",
            "Share of trials whose text contains a sentence reporting the trial's course (`POST_HOC_TEXT`), "
            "before and after `scrub_text`, and the average share of characters the scrub removes.", "",
            md(pd.DataFrame(rows).T), ""]

    desc = lambda f: (f.brief_summary.fillna("") + " " + f.detailed_description.fillna(""))
    a_raw, fail_raw, succ_raw = text_model_auc(desc(train), y_tr, desc(val), y_va)
    a_scr, fail_scr, succ_scr = text_model_auc(desc(train).map(scrub_text), y_tr, desc(val).map(scrub_text), y_va)
    tm = pd.DataFrame({
        "val AUC": [a_raw, a_scr],
        "top words -> terminated": [", ".join(fail_raw), ", ".join(fail_scr)],
        "top words -> completed": [", ".join(succ_raw), ", ".join(succ_scr)],
    }, index=pd.Index(["raw text", "scrubbed text"], name="summary + description"))
    out += ["TF-IDF + logistic regression on summary + description (train -> val). If raw text scores much higher than "
            "scrubbed text, or its top words describe the trial's fate, the raw text leaks.", "", md(tm), ""]

    # 4. censoring
    if args.censoring.exists():
        cens = pd.read_csv(args.censoring).set_index("start_year")
        cens.index = cens.index.astype(str)
        out += ["## 4. Trials still running, by start year", "",
                "From the API at the same snapshot (`src/censoring_check.py`). `ongoing_share` = still running among "
                "trials with a known status. The cohort ends at the last year where this stays near 5%.", "",
                md(cens), ""]

    # 5. split
    sp = cohort.groupby("split").agg(trials=("nct_id", "size"), success_rate=(TARGET, "mean"),
                                     first_year=("start_date", lambda s: str(s.dt.year.min())),
                                     last_year=("start_date", lambda s: str(s.dt.year.max()))).reindex(list(SPLITS))
    out += ["## 5. Temporal split", "", md(sp), ""]

    # 6. when did train labels become known?
    rows = {}
    for name, (lo, _) in SPLITS.items():
        if name == "train":
            continue
        known = outcome_known_by(train, f"{lo}-01-01")
        rows[f"ended on/after {lo}-01-01 ({name} start)"] = {
            "all train": 1 - known.mean(), "terminated": 1 - known[y_tr == 0].mean(), "completed": 1 - known[y_tr == 1].mean()}
    out += ["## 6. Train labels that resolved after a later split started", "",
            "Share of train trials whose outcome was not yet known when the val/test period began. The share is the "
            "same for both classes, so the label mix is not distorted, but identity features (drug, sponsor) could "
            "carry knowledge from the future. `split.outcome_known_by` lets Phase 5 retrain on known-by-then trials "
            "only as a sensitivity check.", "", md(pd.DataFrame(rows).T), ""]

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
