"""Write reports/labels.md: label counts, the manual audit, and agreement with TOP.

Inputs:
    data/processed/labels.parquet          (src/label.py)
    data/processed/trials/                 (src/parse.py)
    data/external/top/phase_*.csv          TOP benchmark (Fu et al. 2022), from
        https://github.com/futianfan/clinical-trial-outcome-prediction/tree/main/data
    reports/label_audit_sample.csv         held-out audit sample with verdicts

Usage:
    python src/label_report.py
"""

from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd
from sklearn.metrics import cohen_kappa_score

LABELS = ["label_strict", "label_broad", "label_hybrid", "label_pvalue"]


def md(df: pd.DataFrame, floatfmt: str = ".3f") -> str:
    """DataFrame -> GitHub markdown table (no tabulate dependency)."""
    def cell(v) -> str:
        if isinstance(v, float):
            return "" if pd.isna(v) else (f"{v:,.0f}" if v.is_integer() and abs(v) >= 2 else format(v, floatfmt))
        if isinstance(v, int):
            return f"{v:,}"
        return str(v).replace("|", "\\|").replace("\n", " ")
    head = [str(df.index.name or "")] + [str(c) for c in df.columns]
    lines = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for idx, row in df.iterrows():
        lines.append("| " + " | ".join([cell(idx)] + [cell(v) for v in row]) + " |")
    return "\n".join(lines)


def load_top(top_dir: Path) -> pd.DataFrame | None:
    files = sorted(top_dir.glob("phase_*.csv"))
    if not files:
        return None
    top = pd.concat([pd.read_csv(f, usecols=["nctid", "status", "label"]) for f in files], ignore_index=True)
    return top.drop_duplicates("nctid").rename(columns={"nctid": "nct_id", "label": "top_label", "status": "top_status"})


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--labels", default="data/processed/labels.parquet", type=Path)
    ap.add_argument("--trials", default="data/processed/trials", type=Path)
    ap.add_argument("--top", default="data/external/top", type=Path)
    ap.add_argument("--audit", default="reports/label_audit_sample.csv", type=Path)
    ap.add_argument("--out", default="reports/labels.md", type=Path)
    args = ap.parse_args()

    lab = pd.read_parquet(args.labels)
    trials = pd.read_parquet(args.trials, columns=["nct_id", "lead_sponsor_class", "has_results"])
    c = lab[lab.in_cohort]
    out: list[str] = ["# Label report", "", "_Generated by `src/label_report.py`. Do not edit by hand._", ""]

    # 1. cohort
    funnel = lab.exclusion_reason.fillna("in cohort").value_counts().rename("trials").to_frame()
    out += ["## 1. Cohort", "", md(funnel), ""]

    # 2. reasons
    term = c[c.overall_status.eq("TERMINATED")]
    reasons = term.stop_category.value_counts().rename("trials").to_frame()
    reasons["share"] = reasons.trials / reasons.trials.sum()
    reasons["counts as"] = reasons.index.map(
        lambda k: "failure" if k in ("safety", "efficacy", "dsmb") else "success" if k == "early_benefit" else "neutral"
    )
    out += ["## 2. Why terminated trials stopped (cohort)", "", md(reasons), ""]

    # 3. label sizes
    sizes = pd.DataFrame({name: {"n": c[name].notna().sum(), "success rate": c[name].mean()} for name in LABELS}).T
    by_phase = c.groupby("phase")[LABELS].mean()
    by_phase.insert(0, "n", c.groupby("phase").size())
    by_year = c.groupby(c.start_year.astype(int).astype(str).rename("start_year"))[["label_broad", "label_hybrid"]].mean()
    by_year.insert(0, "n", c.groupby("start_year").size())
    out += ["## 3. Labels", "", md(sizes), "", "Success rate by phase:", "", md(by_phase), "",
            "Success rate by start year:", "", md(by_year), ""]

    # 4. audit
    if args.audit.exists():
        a = pd.read_csv(args.audit)
        verdicts = a.claude_verdict.value_counts().rename("trials").to_frame()
        verdicts["share"] = verdicts.trials / len(a)
        out += ["## 4. Manual audit of `why_stopped` rules", "",
                f"{len(a)} terminated trials (start years 2005-2019), drawn after the rules were tuned on a separate "
                "200-trial dev sample (`reports/label_dev_sample.csv`). Verdicts were recorded before the rules were "
                "corrected for the errors found, so the accuracy below is an honest held-out estimate for the "
                "earlier rules. `team_verdict` is left blank for a second reviewer.", "",
                md(verdicts), ""]
        wrong = a[a.claude_verdict.ne("correct")][["stop_category", "claude_correct_category", "claude_note", "why_stopped"]]
        wrong = wrong.assign(why_stopped=wrong.why_stopped.str.slice(0, 120))
        out += [md(wrong.fillna("")), ""]

    # 5. TOP agreement
    top = load_top(args.top)
    if top is not None:
        m = top.merge(c, on="nct_id")
        rows = {}
        for name in LABELS:
            x = m.dropna(subset=[name])
            rows[name] = {"n": len(x), "agreement": (x[name] == x.top_label).mean(), "kappa": cohen_kappa_score(x[name], x.top_label)}
        agree = pd.DataFrame(rows).T
        by_status = m.groupby("overall_status").top_label.agg(["size", "mean"]).rename(columns={"mean": "TOP success rate"})
        by_cat = m[m.overall_status.eq("TERMINATED")].groupby("stop_category").top_label.agg(["size", "mean"]).rename(
            columns={"mean": "TOP success rate"})
        out += ["## 5. Agreement with the TOP benchmark", "",
                f"TOP has {len(top)} unique trials; {len(m)} are in our cohort.", "", md(agree), "",
                "TOP label by our status:", "", md(by_status), "",
                "TOP label for terminated trials, by our reason category:", "", md(by_cat), ""]

    # 6. p-value coverage
    cc = c[c.overall_status.eq("COMPLETED")].merge(trials, on="nct_id")
    cov = cc.groupby("lead_sponsor_class").agg(trials=("nct_id", "size"), share_with_pvalues=("label_pvalue", lambda s: s.notna().mean()))
    out += ["## 6. Who posts primary-outcome p-values (completed cohort trials)", "",
            "`label_hybrid` can only call a completed trial a failure if it posted p-values, so its "
            "failure rate depends on this share.", "", md(cov.sort_values("trials", ascending=False)), ""]

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
